const GIRLDLE_ATTRS = ["weapon", "element", "role", "squad"];
const GIRLDLE_MAX_GUESSES = 8;

const GIRLDLE_STORAGE_KEY = "girldleState";
const GIRLDLE_STREAK_KEY = "girldleStreak";

function girldleTodayUTC() {
  return new Date().toISOString().slice(0, 10);
}

function girldleGetDailyAnswer() {
  // Deterministic daily pick based on date string hash
  const dateStr = girldleTodayUTC();
  let hash = 0;
  for (let i = 0; i < dateStr.length; i++) {
    hash = (hash * 31 + dateStr.charCodeAt(i)) | 0;
  }
  return GIRLDLE_DOLLS[Math.abs(hash) % GIRLDLE_DOLLS.length];
}

function girldleLoadState() {
  try {
    const raw = localStorage.getItem(GIRLDLE_STORAGE_KEY);
    if (!raw) return null;
    const state = JSON.parse(raw);
    if (state.date !== girldleTodayUTC()) return null;
    return state;
  } catch {
    return null;
  }
}

function girldleSaveState(guesses, solved) {
  localStorage.setItem(
    GIRLDLE_STORAGE_KEY,
    JSON.stringify({
      date: girldleTodayUTC(),
      guesses: guesses.map((g) => g.name),
      solved,
    }),
  );
}

// ── Streak tracking ──
function girldleLoadStreak() {
  try {
    const raw = localStorage.getItem(GIRLDLE_STREAK_KEY);
    if (!raw) return { current: 0, best: 0, lastDate: null };
    return JSON.parse(raw);
  } catch {
    return { current: 0, best: 0, lastDate: null };
  }
}

function girldleSaveStreak(streak) {
  localStorage.setItem(GIRLDLE_STREAK_KEY, JSON.stringify(streak));
}

function girldleUpdateStreak(solved) {
  const streak = girldleLoadStreak();
  const today = girldleTodayUTC();
  if (streak.lastDate === today) return streak; // already updated today

  const yesterday = new Date(Date.now() - 86400000).toISOString().slice(0, 10);
  if (solved) {
    streak.current = streak.lastDate === yesterday ? streak.current + 1 : 1;
    streak.best = Math.max(streak.best, streak.current);
  } else {
    streak.current = 0;
  }
  streak.lastDate = today;
  girldleSaveStreak(streak);
  return streak;
}

// ── Share results ──
function girldleShareResults() {
  const date = girldleTodayUTC();
  const solved = girldleSolved;
  const count = girldleGuesses.length;
  const header = `Girldle ${date} ${solved ? count : "X"}/${GIRLDLE_MAX_GUESSES}`;

  const rows = girldleGuesses.map((guess) => {
    const nameSquare =
      guess.name === girldleAnswer.name ? "\u{1f7e9}" : "\u{1f7e5}";
    const results = girldleCompare(guess, girldleAnswer);
    return (
      nameSquare +
      results
        .map((r) => {
          if (r.match === "correct") return "\u{1f7e9}";
          if (r.match === "partial") return "\u{1f7e8}";
          return "\u{1f7e5}";
        })
        .join("")
    );
  });

  const text =
    header +
    "\n" +
    rows.join("\n") +
    "\nhttps://antistrategie.github.io/girl-kickers/unit-builder/#girldle";
  navigator.clipboard.writeText(text).then(() => {
    showToast("Results copied to clipboard!");
  });
}

function girldleCompare(guess, answer) {
  return GIRLDLE_ATTRS.map((attr) => {
    const gVal = guess[attr];
    const aVal = answer[attr];
    let match = "wrong";
    if (gVal === aVal) {
      match = "correct";
    } else if (attr === "element") {
      // Handle dual elements like "Burn / Freeze"
      const gParts = gVal.split(" / ");
      const aParts = aVal.split(" / ");
      if (
        gParts.some((g) => aParts.includes(g)) ||
        aParts.some((a) => gParts.includes(a))
      ) {
        match = "partial";
      }
    }
    return { attr, value: gVal, match };
  });
}

function girldleRenderBoard(guesses, answer, solved, failed) {
  const container = document.getElementById("girldleBoard");
  if (!container) return;

  let html = "";

  if (guesses.length === 0) {
    html += `<div class="girldle-intro">`;
    html += `<div class="girldle-intro-title">Guess today's doll</div>`;
    html += `<div class="girldle-intro-hint">4 attributes: weapon, element, role, squad</div>`;
    html += `</div>`;
  } else {
    // Header row
    html += `<div class="girldle-row girldle-header">`;
    html += `<div class="girldle-cell girldle-name-cell">Doll</div>`;
    for (const attr of GIRLDLE_ATTRS) {
      html += `<div class="girldle-cell">${attr.charAt(0).toUpperCase() + attr.slice(1)}</div>`;
    }
    html += `</div>`;

    // Guess rows
    for (const guess of guesses) {
      const results = girldleCompare(guess, answer);
      html += `<div class="girldle-row">`;
      const nameMatch = guess.name === answer.name ? "correct" : "wrong";
      html += `<div class="girldle-cell girldle-name-cell girldle-${nameMatch}">${esc(guess.name)}</div>`;
      for (const r of results) {
        html += `<div class="girldle-cell girldle-${r.match}">${esc(r.value)}</div>`;
      }
      html += `</div>`;
    }
  }

  container.innerHTML = html;

  // Update message
  const msg = document.getElementById("girldleMessage");
  if (solved) {
    msg.innerHTML = `<span class="girldle-win">You got it in ${guesses.length}/${GIRLDLE_MAX_GUESSES}!</span><br>The answer was <strong>${esc(answer.name)}</strong>.`;
  } else if (failed) {
    msg.innerHTML = `<span class="girldle-lose">Out of guesses!</span><br>The answer was <strong>${esc(answer.name)}</strong>.`;
  } else if (guesses.length > 0) {
    msg.textContent = `${guesses.length} / ${GIRLDLE_MAX_GUESSES}`;
  } else {
    msg.textContent = "";
  }
}

function girldleRenderInput(guesses, solved, failed) {
  const actions = document.getElementById("girldleActions");
  if (solved || failed) {
    const nextReset = timeUntilMidnightUTC();
    const streak = girldleUpdateStreak(solved);
    actions.innerHTML = `
      <div class="girldle-end">
        <div class="girldle-end-stats">
          <div class="girldle-stat">
            <div class="girldle-stat-value">${streak.current}</div>
            <div class="girldle-stat-label">Streak</div>
          </div>
          <div class="girldle-stat">
            <div class="girldle-stat-value">${streak.best}</div>
            <div class="girldle-stat-label">Best</div>
          </div>
        </div>
        <button class="btn btn-accent" id="girldleShareBtn" onclick="girldleShareResults()">Share</button>
        <div class="girldle-timer">Next Girldle in ${nextReset}</div>
      </div>
    `;
    return;
  }

  const usedNames = new Set(guesses.map((g) => g.name));
  const available = GIRLDLE_DOLLS.filter((d) => !usedNames.has(d.name)).sort(
    (a, b) => a.name.localeCompare(b.name),
  );

  actions.innerHTML = `
        <div class="girldle-input-row">
            <div class="girldle-autocomplete-wrapper">
                <input type="text" id="girldleInput" placeholder="Type a doll name..." autocomplete="off" />
                <div class="girldle-suggestions" id="girldleSuggestions"></div>
            </div>
            <button class="btn btn-accent" id="girldleGuessBtn" onclick="girldleSubmitGuess()" disabled>Guess</button>
        </div>
    `;

  const input = document.getElementById("girldleInput");
  const suggestions = document.getElementById("girldleSuggestions");
  const guessBtn = document.getElementById("girldleGuessBtn");
  let selectedDoll = null;
  let highlightIdx = -1;

  function showSuggestions() {
    const val = input.value.trim().toLowerCase();

    const matches =
      val.length < 1
        ? available
        : available.filter((d) => d.name.toLowerCase().includes(val));

    if (matches.length === 0) {
      suggestions.innerHTML = "";
      suggestions.style.display = "none";
      return;
    }

    suggestions.style.display = "block";
    suggestions.innerHTML = matches
      .map(
        (d) =>
          `<div class="girldle-suggestion" data-name="${esc(d.name)}">${esc(d.name)}</div>`,
      )
      .join("");

    suggestions.querySelectorAll(".girldle-suggestion").forEach((el) => {
      el.addEventListener("click", () => {
        const name = el.dataset.name;
        input.value = name;
        selectedDoll = available.find((d) => d.name === name);
        guessBtn.disabled = false;
        suggestions.style.display = "none";
      });
    });
  }

  input.addEventListener("input", () => {
    selectedDoll = null;
    guessBtn.disabled = true;
    highlightIdx = -1;
    showSuggestions();
  });

  input.addEventListener("focus", showSuggestions);

  input.addEventListener("keydown", (e) => {
    const items = suggestions.querySelectorAll(".girldle-suggestion");
    if (e.key === "ArrowDown") {
      e.preventDefault();
      highlightIdx = Math.min(highlightIdx + 1, items.length - 1);
      items.forEach((el, i) =>
        el.classList.toggle("highlighted", i === highlightIdx),
      );
      if (items[highlightIdx]) {
        input.value = items[highlightIdx].dataset.name;
        selectedDoll = available.find((d) => d.name === input.value);
        guessBtn.disabled = false;
      }
    } else if (e.key === "ArrowUp") {
      e.preventDefault();
      highlightIdx = Math.max(highlightIdx - 1, 0);
      items.forEach((el, i) =>
        el.classList.toggle("highlighted", i === highlightIdx),
      );
      if (items[highlightIdx]) {
        input.value = items[highlightIdx].dataset.name;
        selectedDoll = available.find((d) => d.name === input.value);
        guessBtn.disabled = false;
      }
    } else if (e.key === "Enter") {
      if (selectedDoll) {
        suggestions.style.display = "none";
        girldleSubmitGuess();
      } else if (items.length === 1) {
        input.value = items[0].dataset.name;
        selectedDoll = available.find((d) => d.name === input.value);
        suggestions.style.display = "none";
        girldleSubmitGuess();
      }
    } else {
      highlightIdx = -1;
    }
  });

  // Close suggestions on outside click
  document.addEventListener("click", (e) => {
    if (!e.target.closest(".girldle-autocomplete-wrapper")) {
      suggestions.style.display = "none";
    }
  });

  input.focus();
  showSuggestions();
}

let girldleGuesses = [];
let girldleSolved = false;
let girldleAnswer = null;

function girldleSubmitGuess() {
  const input = document.getElementById("girldleInput");
  const name = input.value.trim();
  const doll = GIRLDLE_DOLLS.find((d) => d.name === name);
  if (!doll) return;
  if (girldleGuesses.some((g) => g.name === name)) return;

  girldleGuesses.push(doll);

  if (doll.name === girldleAnswer.name) {
    girldleSolved = true;
  }

  const failed = !girldleSolved && girldleGuesses.length >= GIRLDLE_MAX_GUESSES;
  girldleSaveState(girldleGuesses, girldleSolved);
  girldleRenderBoard(girldleGuesses, girldleAnswer, girldleSolved, failed);
  girldleRenderInput(girldleGuesses, girldleSolved, failed);
}

function openGirldle() {
  const overlay = document.getElementById("girldleOverlay");
  overlay.classList.add("visible");
  document.body.classList.add("modal-open");
  if (window.location.hash !== "#girldle") {
    history.replaceState(null, "", "#girldle");
  }

  girldleAnswer = girldleGetDailyAnswer();
  girldleGuesses = [];
  girldleSolved = false;

  // Restore saved state
  const saved = girldleLoadState();
  if (saved) {
    for (const name of saved.guesses) {
      const doll = GIRLDLE_DOLLS.find((d) => d.name === name);
      if (doll) girldleGuesses.push(doll);
    }
    girldleSolved = saved.solved;
  }

  const failed = !girldleSolved && girldleGuesses.length >= GIRLDLE_MAX_GUESSES;
  girldleRenderBoard(girldleGuesses, girldleAnswer, girldleSolved, failed);
  girldleRenderInput(girldleGuesses, girldleSolved, failed);
}

function closeGirldle() {
  const overlay = document.getElementById("girldleOverlay");
  overlay.classList.remove("visible");
  document.body.classList.remove("modal-open");
  if (window.location.hash === "#girldle") {
    history.replaceState(null, "", window.location.pathname);
  }
}
